/* =====================================================================
   КАТАЛОГ КНИГ
   Каталог пуст: книги добавляются по одной в список BOOKS_SEED ниже.

   Формат одной строки:
     [ 'Категория', 'Название', 'Автор', розница ₽, опт ₽, 'badge', 'Описание', 'assets/books/xxx.jpg', '#цвет-фона' ]

     Категория — обычное название ("Фикх", "Хадисы" ...). Раздел создаётся сам,
                 как только в нём появится первая книга.
     badge     — 'new' (плашка «Новинка») или '' (без плашки)
     обложка   — путь к фото обложки ("" = рисованная заглушка)
     цвет-фона — основной цвет книги; на его основе рисуется задний план карточки
   ===================================================================== */
window.BOOKS_SEED = [
  // сюда добавляются книги
];

(function () {
  var ICONS = {   // значки известных разделов; для остальных — «книга»
    'Коран и тафсиры': 'quran', 'Хадисы': 'hadith', 'Акыда': 'aqida', 'Фикх': 'fiqh',
    'Жизнеописание пророка ﷺ': 'sira', 'Истории пророков': 'prophets', 'Воспитание души': 'soul', 'Исламские товары': 'goods'
  };
  var cats = [], keyOf = {};
  var seed = window.BOOKS_SEED;

  window.BOOKS = seed.map(function (s, i) {
    if (!(s[0] in keyOf)) {
      keyOf[s[0]] = 'c' + cats.length;
      cats.push({ key: keyOf[s[0]], name: s[0], icon: ICONS[s[0]] || 'book' });
    }
    return {
      id: i + 1, cat: keyOf[s[0]], title: s[1], author: s[2],
      retail: s[3], wholesale: s[4], minOpt: 5,
      badge: s[5] || '', cover: s[7] || '', desc: s[6] || '', img: '', bg: s[8] || ''
    };
  });
  window.CATEGORIES = cats;
})();
